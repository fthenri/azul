async function run() {
  const tasks = [
    { name: "icon-512x512.png", size: 512, bg: "#002046", padding: 0.18 },
    { name: "icon-192x192.png", size: 192, bg: "#002046", padding: 0.18 },
    { name: "apple-touch-icon.png", size: 180, bg: "#002046", padding: 0.18 },
    { name: "icon-96x96.png", size: 96, bg: "#002046", padding: 0.18 },
    { name: "icon-48x48.png", size: 48, bg: "#002046", padding: 0.18 },
  ];

  for (const t of tasks) {
    const svg = createSvgIcon(t.size, t.padding, t.bg);
    const dest = path.join(iconsDir, t.name);
    await sharp(Buffer.from(svg)).png().toFile(dest);
    console.log(`Gerado: ${t.name} (${t.size}x${t.size})`);
  }

  // Maskable icon com padding maior
  const maskableSvg = createMaskableSvgIcon(512);
  await sharp(Buffer.from(maskableSvg))
    .png()
    .toFile(path.join(iconsDir, "icon-maskable-512x512.png"));
  console.log("Gerado: icon-maskable-512x512.png");

  // Também atualizar src/app/icon.png com o novo logo oficial do Pulso
  const appIconSvg = createSvgIcon(512, 0.18, "#002046");
  await sharp(Buffer.from(appIconSvg))
    .png()
    .toFile(path.join(appDir, "icon.png"));
  console.log("Atualizado: src/app/icon.png");
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
